#!/usr/bin/env node
/**
 * Regenerates the proposal index in docs/proposals/README.md.
 *
 * The index is derived from the files themselves, between the INDEX markers, so
 * it cannot drift out of date the way a hand-maintained list does. Run it after
 * adding or re-titling a proposal:
 *
 *   node scripts/index-proposals.mjs
 *   node scripts/index-proposals.mjs --check    # fails if the index is stale
 */
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIR = 'docs/proposals'
const README = join(DIR, 'README.md')
const START = '<!-- INDEX:START -->'
const END = '<!-- INDEX:END -->'

const AREAS = ['operations', 'events', 'community', 'design', 'platform', 'growth']

function read(file) {
	const text = readFileSync(join(DIR, file), 'utf8')
	const front = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? ''
	const field = (name) => new RegExp(`^${name}:\\s*(.+)$`, 'm').exec(front)?.[1]?.trim() ?? ''

	// The effort cell often carries a note after the size; keep only the size.
	const effortCell = /\|\s*\*\*Effort\*\*\s*\|\s*([^|]*)\|/.exec(text)?.[1]?.trim() ?? ''
	const effort = /^(XL|L|M|S)\b/.exec(effortCell)?.[1] ?? field('effort')

	return {
		file,
		number: file.slice(0, 3),
		title: /^#\s+\d+\s+—\s+(.+)$/m.exec(text)?.[1]?.trim() || field('title'),
		area: field('area'),
		status: field('status') || 'draft',
		effort,
		words: text.split(/\s+/).filter(Boolean).length,
	}
}

const onDisk = readdirSync(DIR)
	.filter((f) => /^\d{3}-.+\.md$/.test(f))
	.sort()
	.map(read)

/**
 * A proposal under review lives on its own branch, so it is not on disk here.
 * Listing only merged files would make the index look nearly empty while two
 * dozen proposals are open — the opposite of useful. Ask GitHub for the rest.
 *
 * Network failure is not fatal: the index degrades to what is merged, and says so.
 */
async function openProposals() {
	let token
	try {
		const out = execFileSync('git', ['credential', 'fill'], {
			input: 'protocol=https\nhost=github.com\n\n',
			encoding: 'utf8',
		})
		token = /^password=(.+)$/m.exec(out)?.[1]?.trim()
	} catch {
		return null
	}
	if (!token) return null

	try {
		const response = await fetch(
			'https://api.github.com/repos/tairqaldy/qairuhub-web/pulls?state=open&per_page=100',
			{
				headers: {
					Authorization: `Bearer ${token}`,
					Accept: 'application/vnd.github+json',
					'User-Agent': 'qairuhub-proposals',
				},
			},
		)
		if (!response.ok) return null
		const pulls = await response.json()

		return pulls
			.filter((pr) => pr.head.ref.startsWith('proposal/'))
			.map((pr) => {
				const file = `${pr.head.ref.replace('proposal/', '')}.md`
				return {
					file,
					number: file.slice(0, 3),
					// Strip both the PR prefix and a leading "019 — " that a few
					// titles carry, so the number is not printed twice.
					title: pr.title.replace(/^Proposal:\s*/, '').replace(/^\d{3}\s*—\s*/, ''),
					area: (pr.labels ?? []).map((l) => l.name).find((n) => AREAS.includes(n)) ?? '',
					status: `[in review](${pr.html_url})`,
					effort: '',
					words: 0,
					review: true,
				}
			})
	} catch {
		return null
	}
}

const inReview = (await openProposals()) ?? []
const merged = new Set(onDisk.map((p) => p.number))
const proposals = [...onDisk, ...inReview.filter((p) => !merged.has(p.number))].sort((a, b) =>
	a.number.localeCompare(b.number),
)

const lines = []
for (const area of AREAS) {
	const inArea = proposals.filter((p) => p.area === area)
	if (!inArea.length) continue

	lines.push('', `### ${area[0].toUpperCase()}${area.slice(1)}`, '')
	lines.push('| | Proposal | Effort | Status |', '|---|---|---|---|')
	for (const p of inArea) {
		lines.push(`| ${p.number} | [${p.title}](${p.file}) | ${p.effort || '—'} | ${p.status} |`)
	}
}

const uncategorised = proposals.filter((p) => !AREAS.includes(p.area))
if (uncategorised.length) {
	lines.push('', '### Uncategorised', '')
	lines.push('| | Proposal | Effort | Status |', '|---|---|---|---|')
	for (const p of uncategorised) {
		lines.push(`| ${p.number} | [${p.title}](${p.file}) | ${p.effort || '—'} | ${p.status} |`)
	}
}

const words = proposals.reduce((sum, p) => sum + p.words, 0)
const reviewing = proposals.filter((p) => p.review).length
lines.push(
	'',
	`${proposals.length} proposals` +
		(reviewing ? `, ${reviewing} still open for review` : '') +
		(words ? `, roughly ${Math.round(words / 1000)},000 words merged` : '') +
		'. Generated by `node scripts/index-proposals.mjs` — do not edit by hand.',
	'',
)

const current = readFileSync(README, 'utf8')
const before = current.slice(0, current.indexOf(START) + START.length)
const after = current.slice(current.indexOf(END))
const next = `${before}\n${lines.join('\n')}\n${after}`

if (process.argv.includes('--check')) {
	if (next !== current) {
		console.error('The proposal index is stale. Run: node scripts/index-proposals.mjs')
		process.exit(1)
	}
	console.log('proposal index: up to date')
} else {
	writeFileSync(README, next)
	console.log(`indexed ${proposals.length} proposals`)
}
